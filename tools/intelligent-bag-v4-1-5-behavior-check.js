const fs=require('fs'),vm=require('vm');
const catalog=JSON.parse(fs.readFileSync('data/catalog.json','utf8'));
const pricing=catalog.pricing;
const context={window:{FORNO_PRICING:pricing},console}; vm.createContext(context);
vm.runInContext(fs.readFileSync('js/variant-commerce-v4-1.js','utf8'),context);
vm.runInContext(fs.readFileSync('js/intelligent-bag-v4-1-5.js','utf8'),context);
const api=context.window.FORNO_INTELLIGENT_BAG;
const byId=new Map(catalog.products.map(p=>[p.id,p]));
let n=0; const ok=(name,v)=>{if(!v)throw new Error(name); console.log('PASS',name);n++;};
const pizza=byId.get('margherita');
const second=byId.get('quatro-formaggi');
const drink=byId.get('coca-2l');
const item={id:'x',pizzaId:pizza.id,pizza2Id:null,productType:'pizza',size:'media',crust:'tradicional',remove:'cebola',notes:'bem assada'};
ok('pizza editable',api.canEdit(item)===true);
ok('drink not editable',api.canEdit({productType:'bebida',pizzaId:drink.id})===false);
ok('three size choices',api.sizeChoices(pizza).length===3);
ok('half-and-half common sizes',api.sizeChoices(pizza,second).length===3);
const model=api.editModel(item,pizza); ok('edit model keeps values',model.size==='media'&&model.remove==='cebola'&&model.notes==='bem assada');
ok('crust choices available',model.crusts.length>=1);
console.log(`${n}/${n} intelligent-bag behavior checks passed`);
